"""Write svm_nodes_used.h for a per-scene kernel (-DCYCLES_SVM_NODES_USED -I<out dir>) from a probe log
(scripts/probe_nodes.sh: the patched host prints "SVM nodes used: NODE_A NODE_B ..."): CYCLES_SVM_USED_<type> is 1 for
every used node type and 0 for every other type in kernel/svm/node_types_template.h.
svm_nodes_header.py <kernel tree .../intern/cycles> <probe log> <out dir>"""
import re, sys, os
tree, log, out = sys.argv[1:4]
types = []
for m in re.finditer(r'^SHADER_NODE_TYPE(_DERIVATIVE)?\((\w+)\)', open(f"{tree}/kernel/svm/node_types_template.h").read(), re.M):
    types.append(m.group(2))
    if m.group(1):
        types.append(m.group(2) + "_DERIVATIVE")
line = [l for l in open(log) if "SVM nodes used:" in l]
assert line, "no 'SVM nodes used' line in " + log
used = set(line[-1].split("SVM nodes used:")[1].split())
unknown = used - set(types)
assert not unknown, f"unknown node types {unknown}"
used |= {"NODE_END", "NODE_SHADER_JUMP"}
mc = [l for l in open(log) if "Max closures" in l]
assert mc, "no 'Max closures' line in " + log
max_closures = int(mc[-1].split("Max closures")[1].split()[0])
os.makedirs(out, exist_ok=True)
with open(f"{out}/svm_nodes_used.h", "w") as f:
    f.write(f"/* Generated by scripts/svm_nodes_header.py from {os.path.basename(log)}: {len(used)} of {len(types)} SVM node types. */\n#pragma once\n")
    for t in types:
        f.write(f"#define CYCLES_SVM_USED_{t} {1 if t in used else 0}\n")
    f.write(f"/* the probe's closure count: build with -D__MAX_CLOSURE__ >= this; the host check (CYCLES_SVM_NODES_CHECK) reads it */\n")
    f.write(f"#define CYCLES_SVM_PROBE_MAX_CLOSURES {max_closures}\n")
print(f"{out}/svm_nodes_used.h: {len(used)} of {len(types)} node types used")
